# Run this script for each of the three comparisons by setting COMPARISON:
#   1) "ER_E_vs_NE"      -> ER+/E (dataset 1, blue) vs. ER+/NE (dataset 2, red)
#   2) "TNBC_E_vs_NE"    -> TNBC/E (dataset 1, blue) vs. TNBC/NE (dataset 2, red)
#   3) "ER_E_vs_TNBC_E"  -> ER+/E (dataset 1, blue) vs. TNBC/E (dataset 2, red)

