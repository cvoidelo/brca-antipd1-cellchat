#packages
library(CellChat)
library(patchwork)
library(ComplexHeatmap)

COMPARISON <- "ER_E_vs_NE" # Options: "ER_E_vs_NE", "TNBC_E_vs_NE", "ER_E_vs_TNBC_E"

out_dir <- file.path("results", "comparisons", COMPARISON)
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

# Load pre-computed CellChat objects generated by 01_CellChat.R
load_cc <- function(sub_dir, grp, tag) {
  readRDS(file.path("results", sub_dir, grp, paste0("cellchat_BRCA_Pembro_On_", tag, ".rds")))
}

object.list <- switch(
  COMPARISON,
  "ER_E_vs_NE"     = list(E = load_cc("ER+", "E", "ER_E"),    NE     = load_cc("ER+", "NE", "ER_NE")),
  "TNBC_E_vs_NE"   = list(E = load_cc("TNBC", "E", "TNBC_E"), NE     = load_cc("TNBC", "NE", "TNBC_NE")),
  "ER_E_vs_TNBC_E" = list(ER_E = load_cc("ER+", "E", "ER_E"), TNBC_E = load_cc("TNBC", "E", "TNBC_E"))
)

cellchat <- mergeCellChat(object.list, add.names = names(object.list))

pos.dataset <- names(object.list)[1]
neg.dataset <- names(object.list)[2]

#---
# Part I: Identify altered interactions and cell populations
#---

# Compare total number of interactions and interaction strength (Fig. 2A, Fig. 5A)
gg1 <- compareInteractions(cellchat, show.legend = FALSE, group = c(1, 2))
gg2 <- compareInteractions(cellchat, show.legend = FALSE, group = c(1, 2), measure = "weight")
gg1 + gg2

# Differential circle plots: red = increased in dataset 2 (NE or TNBC/E), blue = increased in dataset 1 (E or ER+/E)
# Generates Fig. 2B (ER_E_vs_NE), Fig. 5B (TNBC_E_vs_NE), and Supp. Fig. 7A (ER_E_vs_TNBC_E)
par(mfrow = c(1, 2), xpd = TRUE)
netVisual_diffInteraction(cellchat, weight.scale = TRUE)
netVisual_diffInteraction(cellchat, weight.scale = TRUE, measure = "weight")

# Optional: differential heatmaps of interaction count and strength
# netVisual_heatmap(cellchat) + netVisual_heatmap(cellchat, measure = "weight")

# Compare outgoing and incoming interaction strength in 2D space (scaled across compared datasets)
# Generates Fig. 2C (ER_E_vs_NE), Fig. 5C (TNBC_E_vs_NE), and Supp. Fig. 7B (ER_E_vs_TNBC_E)
num.link <- sapply(object.list, function(x) {
  rowSums(x@net$count) + colSums(x@net$count) - diag(x@net$count)
})
weight.MinMax <- c(min(num.link), max(num.link))

gg <- lapply(seq_along(object.list), function(i) {
  netAnalysis_signalingRole_scatter(object.list[[i]], title = names(object.list)[i], weight.MinMax = weight.MinMax)
})
patchwork::wrap_plots(plots = gg)

#---
# Part II: Identify altered signaling pathways and information flow
#---

# Functional similarity manifold learning and pathway distance ranking (Supp. Fig. 1A–B)
cellchat <- computeNetSimilarityPairwise(cellchat, type = "functional")
cellchat <- netEmbedding(cellchat, type = "functional")
cellchat <- netClustering(cellchat, type = "functional")

rankSimilarity(cellchat, type = "functional") # Supp. Fig. 1A (ER+) and Supp. Fig. 1B (TNBC)

# Compare relative (stacked = TRUE) and absolute (stacked = FALSE) information flow across pathways
# Generates Fig. 3A (ER_E_vs_NE), Supp. Fig. 4A (TNBC_E_vs_NE), and Fig. 7A (ER_E_vs_TNBC_E)
gg1 <- rankNet(cellchat, mode = "comparison", measure = "weight", stacked = TRUE, do.stat = TRUE)
gg2 <- rankNet(cellchat, mode = "comparison", measure = "weight", stacked = FALSE, do.stat = TRUE)
gg1 + gg2

# Compare outgoing, incoming, and overall signaling patterns across cell populations
pathway.union <- union(object.list[[1]]@netP$pathways, object.list[[2]]@netP$pathways)

# Outgoing patterns: Supp. Fig. 2B (ER+) and Supp. Fig. 3B (TNBC)
ht1_out <- netAnalysis_signalingRole_heatmap(object.list[[1]], pattern = "outgoing", signaling = pathway.union, title = names(object.list)[1], width = 10, height = 12)
ht2_out <- netAnalysis_signalingRole_heatmap(object.list[[2]], pattern = "outgoing", signaling = pathway.union, title = names(object.list)[2], width = 10, height = 12)
draw(ht1_out + ht2_out, ht_gap = unit(0.5, "cm"))

# Incoming patterns: Supp. Fig. 2A (ER+) and Supp. Fig. 3A (TNBC)
ht1_in <- netAnalysis_signalingRole_heatmap(object.list[[1]], pattern = "incoming", signaling = pathway.union, title = names(object.list)[1], width = 10, height = 12, color.heatmap = "GnBu")
ht2_in <- netAnalysis_signalingRole_heatmap(object.list[[2]], pattern = "incoming", signaling = pathway.union, title = names(object.list)[2], width = 10, height = 12, color.heatmap = "GnBu")
draw(ht1_in + ht2_in, ht_gap = unit(0.5, "cm"))

# Overall patterns (outgoing + incoming): Fig. 2E (ER+) and Fig. 5E (TNBC)
ht1_all <- netAnalysis_signalingRole_heatmap(object.list[[1]], pattern = "all", signaling = pathway.union, title = names(object.list)[1], width = 10, height = 12, color.heatmap = "OrRd")
ht2_all <- netAnalysis_signalingRole_heatmap(object.list[[2]], pattern = "all", signaling = pathway.union, title = names(object.list)[2], width = 10, height = 12, color.heatmap = "OrRd")
draw(ht1_all + ht2_all, ht_gap = unit(0.5, "cm"))

