# Part III: Identify up- and down-regulated L-R pairs
#---

# Comparative bubble plots across conditions
# Note: sources.use and targets.use were adjusted to the specific sender/receiver populations
# evaluated in Fig. 4E (myeloid cells in ER+), Supp. Fig. 6A–B (myeloid and cancer cells in TNBC)
netVisual_bubble(cellchat, sources.use = 1, targets.use = seq_along(levels(cellchat@idents)), comparison = c(1, 2), angle.x = 45)

# Optional: split bubble plots by dataset with higher communication probability
# max.dataset = 1 highlights interactions increased in dataset 1 (E); max.dataset = 2 highlights dataset 2 (NE)
