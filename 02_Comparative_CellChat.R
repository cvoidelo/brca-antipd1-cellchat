# gg2 <- netVisual_bubble(cellchat, sources.use = 1, targets.use = seq_along(levels(cellchat@idents)), comparison = c(1, 2), max.dataset = 2, title.name = paste("Increased in", neg.dataset), angle.x = 45, remove.isolate = TRUE)
# gg1 + gg2

# Side-by-side bubble plots for specific sender populations (Supp. Fig. 8A–B: Fibroblasts)
p1 <- netVisual_bubble(object.list[[1]], sources.use = "Fibroblast", remove.isolate = TRUE, title.name = paste("Fibroblast signaling in", pos.dataset))
p2 <- netVisual_bubble(object.list[[2]], sources.use = "Fibroblast", remove.isolate = TRUE, title.name = paste("Fibroblast signaling in", neg.dataset))
p1 + p2

# Differential expression-based mapping of up- and down-regulated L-R pairs
features.name <- paste0(pos.dataset, ".merged")

cellchat <- identifyOverExpressedGenes(
  cellchat,
  group.dataset = "datasets",
  pos.dataset = pos.dataset,
  features.name = features.name,
  only.pos = FALSE,
  thresh.pc = 0.1,
  thresh.fc = 0.05,
  thresh.p = 0.05,
  group.DE.combined = FALSE
)

net <- netMappingDEG(cellchat, features.name = features.name, variable.all = TRUE)
net.up <- subsetCommunication(cellchat, net = net, datasets = pos.dataset, ligand.logFC = 0.05, receptor.logFC = NULL)
net.down <- subsetCommunication(cellchat, net = net, datasets = neg.dataset, ligand.logFC = -0.05, receptor.logFC = NULL)

# Word clouds of enriched ligands/pathways (Fig. 2D, Fig. 5D, Fig. 7B)
# Left panel: upregulated in pos.dataset (net.up); Right panel: downregulated in pos.dataset (net.down)
computeEnrichmentScore(net.up, species = "human", variable.both = TRUE)
computeEnrichmentScore(net.down, species = "human", variable.both = TRUE)

# Export differential gene tables with statistical metrics
deg_table <- as.data.frame(cellchat@var.features[[features.name]])
gene.up <- extractGeneSubsetFromPair(net.up, cellchat)
gene.down <- extractGeneSubsetFromPair(net.down, cellchat)

genes_up_names <- if (is.data.frame(gene.up)) gene.up$gene.use else gene.up
genes_down_names <- if (is.data.frame(gene.down)) gene.down$gene.use else gene.down

if ("gene" %in% colnames(deg_table)) {
  table_up <- deg_table[deg_table$gene %in% genes_up_names, ]
  table_down <- deg_table[deg_table$gene %in% genes_down_names, ]
} else {
  table_up <- deg_table[rownames(deg_table) %in% genes_up_names, ]
  table_down <- deg_table[rownames(deg_table) %in% genes_down_names, ]
}

write.csv(table_up, file = file.path(out_dir, paste0("DEGs_up_", COMPARISON, ".csv")), row.names = TRUE)
write.csv(table_down, file = file.path(out_dir, paste0("DEGs_down_", COMPARISON, ".csv")), row.names = TRUE)

#---
# Part IV: Compare signaling gene expression distributions across datasets
#---

# Violin plots of pathway-associated ligand/receptor expression across cell types
# Generates Fig. 4A ("SPP1" and "CXCL" in ER+) and Fig. 6B ("CXCL", "GALECTIN", and "IGF" in TNBC)
cellchat@meta$datasets <- factor(cellchat@meta$datasets, levels = names(object.list))
plotGeneExpression(cellchat, signaling = "CXCL", split.by = "datasets", colors.ggplot = TRUE, type = "violin")

# Save merged comparison object
save(object.list, file = file.path(out_dir, paste0("cellchat_object.list_", COMPARISON, ".RData")))
save(cellchat, file = file.path(out_dir, paste0("cellchat_merged_", COMPARISON, ".RData")))

